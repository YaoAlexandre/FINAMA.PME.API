    /// <summary>Entités prêtes à enregistrer : classe, type et compte parent (plus long préfixe existant) renseignés.</summary>
    public static List<CompteComptable> GenererPourTenant(Guid tenantId)
    {
        var comptes = Comptes.Select(c => new CompteComptable
        {
            Id = Guid.NewGuid(),
            TenantId = tenantId,
            Numero = c.Numero,
            Libelle = c.Libelle,
            Classe = (ClasseCompte)(c.Numero[0] - '0'),
            Type = TypeDe(c.Numero),
            EstSysteme = true,
            EstActif = true,
            CreatedAt = DateTime.UtcNow,
        }).ToList();

        var parNumero = comptes.ToDictionary(c => c.Numero);
        foreach (var c in comptes)
            for (var n = c.Numero.Length - 1; n >= 2; n--)
                if (parNumero.TryGetValue(c.Numero[..n], out var parent)) { c.CompteParentId = parent.Id; break; }

        return comptes;
    }

    private static TypeCompte TypeDe(string numero) => numero[0] switch
    {
        '1' or '2' or '3' or '4' => TypeCompte.Bilan,
        '5' => TypeCompte.Tresorerie,
        '6' => TypeCompte.ResultatCharge,
        '7' => TypeCompte.ResultatProduit,
        _ => int.Parse(numero[..2]) % 2 == 1 ? TypeCompte.ResultatCharge : TypeCompte.ResultatProduit,   // classe 8 : impairs = charges
    };
